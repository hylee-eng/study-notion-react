/** 키보드나 메뉴 이름을 보여주는 예시 한 줄 */
export type DemoLine = {
  key: string;        // 왼쪽 박스에 들어갈 글자
  solid?: boolean;    // 검은 박스로 강조할지
  arrow?: string;     // 가운데 기호 (없으면 표시하지 않음)
  text: string;       // 오른쪽 설명
  dim?: boolean;      // 설명을 흐리게 (보조 문구일 때)
};

/** 왼쪽에 짧은 이름, 오른쪽에 설명이 오는 표의 한 줄 */
export type Row = { k: string; v: string };

export type Step = {
  id?: string;          // 바로가기 주소가 필요한 단계에만
  title: string;
  body: string;
  screen?: ScreenKey;   // 화면 재현을 붙일 경우
  caption?: string;     // 화면 바깥에 붙는 해설 (화면이 둘인 경우 비워둠)
  demo?: DemoLine[];
  rows?: Row[];
  note?: string;        // 단계 끝에 붙는 한 줄
};

export type Level = {
  n: number;
  desc: string;       // 검색 결과와 공유 미리보기에 쓰이는 설명
  cardDesc: string;   // 랜딩의 학습 경로 카드에 들어가는 한 줄
  title: string[];      // 줄 단위로 나눠 적으면 넓은 화면에서 그 자리에서 줄바꿈됩니다
  lead: string[];
  minutes: string;
  grade: "입문" | "중급";
  prereq: string;
  color: string;        // 머리 카드 배경
  dark: boolean;        // 배경이 진해서 흰 글씨를 써야 하는지
  analogy?: boolean;    // 관계형·롤업 비유 그림을 넣을지 (레벨 5)
  concept?: {           // 실습 전에 먼저 짚는 개념 카드 (레벨 3)
    badge: string;
    title: string[];
    body: string;
    cta?: { href: string; label: string };
  };
  goalsLead: string[];
  goals: string[];
  stepsLead: string[];
  steps: Step[];
  pitfalls: { title: string; body: string }[];
  checkLead: string[];
  checks: string[];
};

